#!/usr/bin/env python3
"""Hold the org's security configuration records to what is live (#1213).

`security/org-default.json` and `security/org-private.json` are the
reviewable record of the org's code security settings. Nothing applies
them, and before this nothing compared them with the live org either: a
change to a record, or a click in the UI, left the two disagreeing with
nothing red. This is the comparison, in four parts.

1. WHICH live configuration the public record describes is derived,
   never named: the configuration the org applies to new public
   repositories (`.../code-security/configurations/defaults`). No id
   is written into the record, because an id there would be a second
   fact that can disagree.

2. Record against live, BOTH directions. Every field the record states
   must equal the live value, and every live field the record does not
   state is red, except the server's own (SERVER_FIELDS) and the two
   the record names for itself (OWN_FIELDS). Ignoring an unstated live
   field is exactly how a setting changes with nothing red.

3. Every PUBLIC repository in the roster is attached to that
   configuration with status `enforced`. Visibility comes from the org
   listing, because the roster does not carry it.

4. Every PRIVATE repository in the roster has the private shape in
   effect — `security_and_analysis` and its Dependabot alerts setting
   equal what `org-private.json` states — and is NOT attached to the
   public configuration. On a private repository the public shape is
   not refused, it attaches and bills, and an unattached repository
   drifts back by one click. A record field with no repository-level
   reading is not judged here, and the pass line says how many.

A read the token cannot make is CANNOT_JUDGE naming the endpoint and
the grant it needs, never a pass. One red never hides another: every
finding and every blind read is reported before the exit.

Exit 0 when everything agrees; exit 1 on any finding or any CANNOT_JUDGE.
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Protocol

import decoded
import findings
import typed_std

GH = shutil.which("gh") or "gh"

TAG = "audit:security-config"

# Generated by the server for every configuration; never a setting.
SERVER_FIELDS = frozenset({
    "id",
    "url",
    "html_url",
    "created_at",
    "updated_at",
    "target_type",
})
# The record's own: live, the UI named the configuration and wrote its
# description, and security/README.md excepts both.
OWN_FIELDS = frozenset({"name", "description"})

# The grants the audit App needs, named exactly as the App settings page
# names them, so a CANNOT_JUDGE line is the owner's whole instruction.
ORG_GRANT = "organisation permission Administration: read"
REPO_GRANT = "repository permission Administration: read"
LISTING_GRANT = "repository permission Metadata: read"

# Record field -> the key that reports it in a repository's
# `security_and_analysis`. `advanced_security` is the bundle of Code
# Security and Secret Protection; a private repository on a plan
# without the bundle reports the two products, and not the bundle, so
# the bundle's state is read as `code_security` (measured 2026-11-15
# on monumental-archive) and Secret Protection by `secret_scanning`,
# which the record states on its own line.
REPO_KEYS = {
    "advanced_security": "code_security",
    "secret_scanning": "secret_scanning",
    "secret_scanning_push_protection": "secret_scanning_push_protection",
    **{
        key: key
        for key in (
            "secret_scanning_non_provider_patterns",
            "secret_scanning_validity_checks",
            "dependabot_security_updates",
        )
    },
}
# Read from its own endpoint: 204 is enabled, 404 is disabled.
ALERTS_FIELD = "dependabot_alerts"

HTTP_OK = 200
HTTP_NO_CONTENT = 204
HTTP_NOT_FOUND = 404


class Fetch(Protocol):
    """Read one endpoint: (status, body)."""

    def __call__(self, endpoint: str, *, paginate: bool = False) -> tuple[int, object]:
        """Read it."""


@dataclass(frozen=True)
class Records:
    """The two records and the roster's names, as read from the tree.

    A record is the settings object as written; its values are compared
    with live as JSON, never read, so they stay decoded values.
    """

    public: dict[str, object]
    private: dict[str, object]
    roster: tuple[str, ...]


def read_records(public: object, private: object, roster: object) -> Records:
    """Decode the two records and the roster.

    A record that is not an object, or a roster without its names,
    raises `UndecodableError` naming the field.

    Returns:
        The records.

    """
    return Records(
        public=decoded.as_object(public, "org-default.json"),
        private=decoded.as_object(private, "org-private.json"),
        roster=roster_names(roster),
    )


def pages(endpoint: str, body: object) -> list[object]:
    """Flatten a paginated read's pages into one list.

    Returns:
        Every item of every page, in order.

    """
    out: list[object] = []
    for page in decoded.as_array(body, f"{endpoint}: the pages"):
        out.extend(decoded.as_array(page, f"{endpoint}: a page"))
    return out


def gh_fetch(endpoint: str, *, paginate: bool = False) -> tuple[int, object]:
    """Read one endpoint through `gh api`.

    Returns:
        (status, body). Success is 200 with the parsed JSON (pages of a
        paginated read flattened into one list), or 204 when the body
        is empty; failure is the HTTP status gh reports, or 0 when it
        reports none, with None for the body.

    Raises:
        UndecodableError: the body is not strict JSON, or a page of a
            paginated read is not a list; the text names the endpoint.

    """
    args = [GH, "api", endpoint]
    if paginate:
        args += ["--paginate", "--slurp"]
    result = subprocess.run(args, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        match = re.search(r"\(HTTP (\d{3})\)", result.stderr)
        code = typed_std.group(match, 1) if match else None
        return (int(code or "0"), None)
    if not result.stdout.strip():
        return (HTTP_NO_CONTENT, None)
    try:
        body = decoded.load_json(result.stdout)
    except decoded.UndecodableError as err:
        msg = f"{endpoint}: {err}"
        raise decoded.UndecodableError(msg) from None
    return (HTTP_OK, pages(endpoint, body) if paginate else body)


class Verdict:
    """Findings and blind reads, collected so one never hides another."""

    def __init__(self) -> None:
        """Start empty."""
        self.red: list[str] = []
        self.blind: list[str] = []
        self.passed: list[str] = []

    def cannot(self, endpoint: str, status: int, grant: str) -> None:
        """Record a read the token could not make."""
        got = f"HTTP {status}" if status else "no HTTP status"
        self.blind.append(f"CANNOT_JUDGE {endpoint} ({got}) — needs {grant}")


def describe(value: object) -> str:
    """Render a JSON value the way the record writes it.

    Returns:
        Compact JSON with sorted keys.

    """
    return json.dumps(value, sort_keys=True, separators=(",", ":"))


def compare_record(
    record: dict[str, object], live: dict[str, object], cid: object
) -> list[str]:
    """Compare the public record with the live configuration both ways.

    Returns:
        One finding per disagreeing field; empty when they agree.

    """
    found: list[str] = []
    stated = {k: v for k, v in record.items() if k not in OWN_FIELDS}
    for key, want in sorted(stated.items()):
        if key not in live:
            have = f"has no {key}"
        elif live[key] != want:
            have = f"has {describe(live[key])}"
        else:
            continue
        found.append(
            f"org-default.json states {key}={describe(want)}; "
            f"configuration {cid} {have}"
        )
    unstated = set(live) - set(stated) - SERVER_FIELDS - OWN_FIELDS
    found.extend(
        f"configuration {cid} sets {key}={describe(live[key])}, "
        "which org-default.json does not state"
        for key in sorted(unstated)
    )
    return found


def roster_names(roster: object) -> tuple[str, ...]:
    """Read the population's names from the roster.

    Returns:
        The repository names, in roster order.

    Raises:
        UndecodableError: the roster, its population or an entry is
            wrongly shaped, or the population list is absent or empty.

    """
    doc = decoded.as_object(roster, "the roster")
    population = decoded.as_object(doc.get("population", {}), "population")
    repos = population.get("repositories")
    if not decoded.is_array(repos) or not repos:
        msg = "population.repositories is absent or empty"
        raise decoded.UndecodableError(msg)
    names: list[str] = []
    for i, raw in enumerate(repos):
        where = f"population.repositories[{i}]"
        entry = decoded.as_object(raw, where)
        names.append(decoded.as_str(entry.get("repo"), f"{where}.repo"))
    return tuple(names)


def repo_status(sa: dict[str, object], key: str) -> str | None:
    """Read one product's status from `security_and_analysis`.

    A status that is not a string raises `UndecodableError`.

    Returns:
        The status, or None when the repository reports no such key.

    """
    entry = sa.get(key)
    if not decoded.is_object(entry) or "status" not in entry:
        return None
    return decoded.as_str(entry["status"], f"security_and_analysis.{key}.status")


class Audit:
    """One run of the four comparisons against one org."""

    def __init__(self, owner: str, records: Records, fetch: Fetch) -> None:
        """Hold the inputs; nothing is read until `run`."""
        self.owner = owner
        self.records = records
        self.fetch = fetch
        self.verdict = Verdict()
        self.cid: object = None
        # Repository name -> attachment status; None until read.
        self.attached: dict[str, str] | None = None

    def visibility(self) -> dict[str, bool] | None:
        """Read the org listing.

        Returns:
            Repository name -> private, or None when the read was blind.

        Raises:
            UndecodableError: a listed repository is wrongly shaped.

        """
        endpoint = f"orgs/{self.owner}/repos?per_page=100"
        status, listing = self.fetch(endpoint, paginate=True)
        if status != HTTP_OK or not decoded.is_array(listing):
            self.verdict.cannot(endpoint, status, LISTING_GRANT)
            return None
        out: dict[str, bool] = {}
        for i, raw in enumerate(listing):
            where = f"{endpoint}: [{i}]"
            row = decoded.as_object(raw, where)
            private = row.get("private", False)
            if not isinstance(private, bool):
                msg = f"{where}.private is not a boolean"
                raise decoded.UndecodableError(msg)
            out[decoded.as_str(row.get("name"), f"{where}.name")] = private
        return out

    def public_configuration(self) -> dict[str, object] | None:
        """Derive the configuration the org gives new public repositories.

        Returns:
            That configuration, or None after recording why there is none.

        """
        endpoint = f"orgs/{self.owner}/code-security/configurations/defaults"
        status, defaults = self.fetch(endpoint)
        if status != HTTP_OK or not decoded.is_array(defaults):
            self.verdict.cannot(endpoint, status, ORG_GRANT)
            return None
        rows = [
            decoded.as_object(d, f"{endpoint}: [{i}]") for i, d in enumerate(defaults)
        ]
        hits = [
            d.get("configuration")
            for d in rows
            if d.get("default_for_new_repos") in {"all", "public"}
        ]
        hit = hits[0] if len(hits) == 1 else None
        if not decoded.is_object(hit):
            self.verdict.red.append(
                f"{len(hits)} configurations are the default for new public "
                "repositories; org-default.json describes exactly one"
            )
            return None
        return hit

    def judge_configuration(self) -> None:
        """Compare the record with the derived configuration; read its repos."""
        config = self.public_configuration()
        if config is None:
            return
        self.cid = config.get("id")
        found = compare_record(self.records.public, config, self.cid)
        self.verdict.red.extend(found)
        if not found:
            n = len(set(self.records.public) - OWN_FIELDS)
            self.verdict.passed.append(
                f"org-default.json: {n} fields equal configuration {self.cid} "
                "(the default for new public repositories), nothing unstated"
            )
        endpoint = (
            f"orgs/{self.owner}/code-security/configurations/{self.cid}"
            "/repositories?per_page=100"
        )
        status, rows = self.fetch(endpoint, paginate=True)
        if status != HTTP_OK or not decoded.is_array(rows):
            self.verdict.cannot(endpoint, status, ORG_GRANT)
            return
        attached: dict[str, str] = {}
        for i, raw in enumerate(rows):
            where = f"{endpoint}: [{i}]"
            row = decoded.as_object(raw, where)
            repo = decoded.as_object(row.get("repository"), f"{where}.repository")
            name = decoded.as_str(repo.get("name"), f"{where}.repository.name")
            attached[name] = decoded.as_str(row.get("status", "?"), f"{where}.status")
        self.attached = attached

    def judge_public(self, repo: str) -> None:
        """Judge a public member: attached to the configuration, enforced."""
        if self.attached is None:
            return
        cid = self.cid
        state = self.attached.get(repo)
        if state is None:
            self.verdict.red.append(
                f"{repo}: public and not attached to configuration {cid}"
            )
        elif state != "enforced":
            self.verdict.red.append(
                f"{repo}: public and attached to configuration {cid} "
                f"with status {state}, not enforced"
            )
        else:
            self.verdict.passed.append(
                f"{repo}: public, attached to configuration {cid}, enforced"
            )

    def private_findings(self, repo: str) -> list[str] | None:
        """Compare one private repository's effective settings with the record.

        Returns:
            The repository's findings, or None when a read was blind.

        """
        record = self.records.private
        endpoint = f"repos/{self.owner}/{repo}"
        status, body = self.fetch(endpoint)
        sa = body.get("security_and_analysis") if decoded.is_object(body) else None
        if status != HTTP_OK or not decoded.is_object(sa):
            # GitHub omits the block, rather than refusing the read, when
            # the token lacks admin on the repository.
            why = status if status != HTTP_OK else 0
            self.verdict.cannot(f"{endpoint} security_and_analysis", why, REPO_GRANT)
            return None
        found: list[str] = []
        for field, key in REPO_KEYS.items():
            if field not in record:
                continue
            want, live = record[field], repo_status(sa, key)
            if live is None:
                found.append(
                    f"{field}: org-private.json states {want}; "
                    f"the repository reports no {key}"
                )
            elif live != want:
                found.append(
                    f"{field}: org-private.json states {want}; {key} is {live}"
                )
        if ALERTS_FIELD not in record:
            return found
        alerts = f"{endpoint}/vulnerability-alerts"
        status, _ = self.fetch(alerts)
        if status not in {HTTP_NO_CONTENT, HTTP_NOT_FOUND}:
            self.verdict.cannot(alerts, status, REPO_GRANT)
            return None
        live = "enabled" if status == HTTP_NO_CONTENT else "disabled"
        if live != record[ALERTS_FIELD]:
            found.append(
                f"{ALERTS_FIELD}: org-private.json states "
                f"{record[ALERTS_FIELD]}; {alerts} says {live}"
            )
        return found

    def judge_private(self, repo: str) -> None:
        """Judge a private member: the private shape, not the public one."""
        cid = self.cid
        found = self.private_findings(repo)
        on_public = self.attached is not None and repo in self.attached
        if on_public:
            self.verdict.red.append(
                f"{repo}: private and attached to the public configuration "
                f"{cid} — on a private repository that bills"
            )
        if found is None:
            return
        self.verdict.red.extend(f"{repo}: {f}" for f in found)
        if found or on_public or self.attached is None:
            return
        record = self.records.private
        judged = [k for k in record if k in REPO_KEYS or k == ALERTS_FIELD]
        unread = len(set(record) - OWN_FIELDS) - len(judged)
        self.verdict.passed.append(
            f"{repo}: private, {len(judged)} fields equal org-private.json, "
            f"not attached to configuration {cid} "
            f"({unread} fields have no repository-level reading)"
        )

    def run(self) -> Verdict:
        """Run every comparison.

        Returns:
            The collected verdict.

        """
        names = self.records.roster
        private = self.visibility()
        if private is None:
            return self.verdict
        self.judge_configuration()
        for repo in names:
            if repo not in private:
                self.verdict.red.append(
                    f"{repo}: in the roster and not in the org listing — gone, "
                    "or the token cannot see it"
                )
            elif private[repo]:
                self.judge_private(repo)
            else:
                self.judge_public(repo)
        return self.verdict


def report(verdict: Verdict) -> int:
    """Print every pass, finding and blind read.

    Returns:
        The process exit status.

    """
    for line in verdict.passed:
        print(f"{TAG}: {line}")
    for line in verdict.red + verdict.blind:
        findings.finding("", line)
    if verdict.blind:
        findings.finding(
            "",
            f"a blind read is not a pass. Grant the audit App "
            f"{ORG_GRANT} and {REPO_GRANT} (#1213).",
        )
    if verdict.red:
        findings.finding(
            "",
            "reconcile security/*.json with the live settings, or put "
            "the live settings back (security/README.md)",
        )
    return 1 if verdict.red or verdict.blind else 0


class Args(argparse.Namespace):
    """The command line, typed where argparse writes it."""

    owner: str
    record: Path
    private_record: Path
    roster: Path


def main(argv: list[str] | None = None, fetch: Fetch = gh_fetch) -> int:
    """Load the records and the roster, then judge them against live.

    Returns:
        The process exit status.

    """
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--owner", required=True)
    parser.add_argument("--record", type=Path, required=True)
    parser.add_argument("--private-record", type=Path, required=True)
    parser.add_argument("--roster", type=Path, required=True)
    args = parser.parse_args(argv, namespace=Args())
    try:
        records = read_records(
            public=decoded.load_json(args.record.read_bytes()),
            private=decoded.load_json(args.private_record.read_bytes()),
            roster=decoded.load_json(args.roster.read_bytes()),
        )
        verdict = Audit(args.owner, records, fetch).run()
    except (OSError, ValueError) as err:
        findings.finding("", f"cannot read an input: {err}")
        return 1
    return report(verdict)


if __name__ == "__main__":
    sys.exit(main())
