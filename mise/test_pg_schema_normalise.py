#!/usr/bin/env python3
"""Table tests for lint:pg-schema's normaliser, both directions (#896).

The property the normalisation exists for is the one a naive diff gets
wrong: a pure line-number shift must NOT change the surface, and a
signature change MUST. Both are planted here against REAL `cargo pgrx
schema` output, never a hand-written fixture — RAW below is edtf-postgres
at edtf@4644060 (v1.3.3), generated by `lint:pg-schema` at pg18 with
cargo-pgrx 0.19.3, and EDTF_SNAPSHOT is edtf's tracked
`crates/edtf-postgres/schema.snapshot.sql` at the same commit. The first
row is that the one normalises to the other byte for byte, which is what
lets the belt task replace edtf's script without a chore.

Each plant is the transformation measured end to end on that tree:
a blank line inserted above `edtf_level` moved every later annotation by
one (`-- crates/edtf-postgres/src/lib.rs:42` became `:43`) and the task
stayed green; a second argument added to `edtf_level` reddened it on
exactly that statement.

Mutation-checked, one mutant at a time against the normaliser: the
`--` strip removed reds 3 rows, the `/* */` strip made line-local reds 4,
whitespace kept un-collapsed reds 4, the sort removed reds 1 (the
reorder row — edtf's items happen to generate in sorted order), and the
empty-surface guard removed reds 2.

stdlib `unittest`, matching the other mise/test_*.py.
"""

import importlib.util
import io
import re
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

_SPEC = importlib.util.spec_from_file_location(
    "pg_schema_normalise",
    Path(__file__).with_name("pg-schema-normalise.py"),
)
pg_schema_normalise = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(pg_schema_normalise)
normalise = pg_schema_normalise.normalise

RAW = """\
/* <begin connected objects> */
/*
This file is auto generated by pgrx.

The ordering of items is not stable, it is driven by a dependency graph.
*/
/* </end connected objects> */

/* <begin connected objects> */
-- crates/edtf-postgres/src/lib.rs:52
-- edtf_postgres::edtf_canonical
CREATE  FUNCTION "edtf_canonical"(
\t"input" TEXT /* & str */
) RETURNS TEXT /* Option < String > */
IMMUTABLE STRICT PARALLEL SAFE
LANGUAGE c /* Rust */
AS 'MODULE_PATHNAME', 'edtf_canonical_wrapper';
/* </end connected objects> */

/* <begin connected objects> */
-- crates/edtf-postgres/src/lib.rs:42
-- edtf_postgres::edtf_level
CREATE  FUNCTION "edtf_level"(
\t"input" TEXT /* & str */
) RETURNS INT /* Option < i32 > */
IMMUTABLE STRICT PARALLEL SAFE
LANGUAGE c /* Rust */
AS 'MODULE_PATHNAME', 'edtf_level_wrapper';
/* </end connected objects> */

/* <begin connected objects> */
-- crates/edtf-postgres/src/lib.rs:91
-- edtf_postgres::edtf_max
CREATE  FUNCTION "edtf_max"(
\t"input" TEXT /* & str */
) RETURNS date /* Option < Date > */
IMMUTABLE STRICT PARALLEL SAFE
LANGUAGE c /* Rust */
AS 'MODULE_PATHNAME', 'edtf_max_wrapper';
/* </end connected objects> */

/* <begin connected objects> */
-- crates/edtf-postgres/src/lib.rs:80
-- edtf_postgres::edtf_min
CREATE  FUNCTION "edtf_min"(
\t"input" TEXT /* & str */
) RETURNS date /* Option < Date > */
IMMUTABLE STRICT PARALLEL SAFE
LANGUAGE c /* Rust */
AS 'MODULE_PATHNAME', 'edtf_min_wrapper';
/* </end connected objects> */

/* <begin connected objects> */
-- crates/edtf-postgres/src/lib.rs:108
-- edtf_postgres::edtf_relation
CREATE  FUNCTION "edtf_relation"(
\t"a" TEXT, /* & str */
\t"b" TEXT /* & str */
) RETURNS TEXT[] /* :: std :: option :: Option < Vec < String > > */
IMMUTABLE STRICT PARALLEL SAFE
LANGUAGE c /* Rust */
AS 'MODULE_PATHNAME', 'edtf_relation_wrapper';
/* </end connected objects> */

/* <begin connected objects> */
-- crates/edtf-postgres/src/lib.rs:32
-- edtf_postgres::edtf_valid
CREATE  FUNCTION "edtf_valid"(
\t"input" TEXT /* & str */
) RETURNS bool /* bool */
IMMUTABLE STRICT PARALLEL SAFE
LANGUAGE c /* Rust */
AS 'MODULE_PATHNAME', 'edtf_valid_wrapper';
/* </end connected objects> */

"""

EDTF_SNAPSHOT = (
    'CREATE FUNCTION "edtf_canonical"( "input" TEXT ) RETURNS '
    "TEXT IMMUTABLE STRICT PARALLEL SAFE LANGUAGE c AS "
    "'MODULE_PATHNAME', 'edtf_canonical_wrapper';"
    "\n"
    'CREATE FUNCTION "edtf_level"( "input" TEXT ) RETURNS INT '
    "IMMUTABLE STRICT PARALLEL SAFE LANGUAGE c AS "
    "'MODULE_PATHNAME', 'edtf_level_wrapper';"
    "\n"
    'CREATE FUNCTION "edtf_max"( "input" TEXT ) RETURNS date '
    "IMMUTABLE STRICT PARALLEL SAFE LANGUAGE c AS "
    "'MODULE_PATHNAME', 'edtf_max_wrapper';"
    "\n"
    'CREATE FUNCTION "edtf_min"( "input" TEXT ) RETURNS date '
    "IMMUTABLE STRICT PARALLEL SAFE LANGUAGE c AS "
    "'MODULE_PATHNAME', 'edtf_min_wrapper';"
    "\n"
    'CREATE FUNCTION "edtf_relation"( "a" TEXT, "b" TEXT ) '
    "RETURNS TEXT[] IMMUTABLE STRICT PARALLEL SAFE LANGUAGE c AS "
    "'MODULE_PATHNAME', 'edtf_relation_wrapper';"
    "\n"
    'CREATE FUNCTION "edtf_valid"( "input" TEXT ) RETURNS bool '
    "IMMUTABLE STRICT PARALLEL SAFE LANGUAGE c AS "
    "'MODULE_PATHNAME', 'edtf_valid_wrapper';"
    "\n"
)

BLOCK = "/* <begin connected objects> */"


def shift_lines(text: str, by: int) -> str:
    """Move every source-location annotation, as an edit above them does.

    Returns:
        The text with each `-- <path>.rs:<line>` annotation moved by `by`.

    """
    return re.sub(
        r"(\.rs:)(\d+)",
        lambda m: f"{m.group(1)}{int(m.group(2)) + by}",
        text,
    )


def reorder(text: str) -> str:
    """Reverse pgrx's item blocks, the order its header calls unstable.

    Returns:
        The same blocks, last first.

    """
    head, *blocks = text.split(BLOCK)
    return head + "".join(BLOCK + b for b in reversed(blocks))


def add_argument(text: str) -> str:
    """Give `edtf_level` a second argument, the planted signature change.

    Returns:
        The text as pgrx generates it for `fn edtf_level(input: &str,
        _strict: bool)`.

    Raises:
        ValueError: when the captured RAW no longer carries the
            signature being replaced, so the plant would be a no-op.

    """
    before = 'CREATE  FUNCTION "edtf_level"(\n\t"input" TEXT /* & str */\n)'
    after = (
        'CREATE  FUNCTION "edtf_level"(\n\t"input" TEXT, /* & str */\n'
        '\t"_strict" bool /* bool */\n)'
    )
    if before not in text:
        message = "the captured RAW no longer carries edtf_level's signature"
        raise ValueError(message)
    return text.replace(before, after)


def run_main(argv: list[str]) -> tuple[int, str, str]:
    """Call the entry point the task calls, capturing both streams.

    Returns:
        The exit status, stdout and stderr.

    """
    out, err = io.StringIO(), io.StringIO()
    with redirect_stdout(out), redirect_stderr(err):
        status = pg_schema_normalise.main(argv)
    return status, out.getvalue(), err.getvalue()


def write(text: str) -> str:
    """Write a generated-schema file where the task would.

    Returns:
        Its path.

    """
    path = Path(tempfile.mkdtemp()) / "raw.sql"
    path.write_text(text, encoding="utf-8")
    return str(path)


class Unchanged(unittest.TestCase):
    """What must NOT diff: everything that is not the surface."""

    def test_edtf_raw_normalises_to_its_tracked_snapshot(self) -> None:
        """Real pgrx output reduces to edtf's tracked file, byte for byte."""
        self.assertEqual(normalise(RAW), EDTF_SNAPSHOT)

    def test_line_number_shift_is_invisible(self) -> None:
        """The property a naive diff gets wrong: a blank line above."""
        shifted = shift_lines(RAW, 1)
        self.assertNotEqual(shifted, RAW)
        self.assertEqual(normalise(shifted), normalise(RAW))

    def test_item_order_is_invisible(self) -> None:
        """The order pgrx's own header calls unstable."""
        moved = reorder(RAW)
        self.assertNotEqual(moved, RAW)
        self.assertEqual(normalise(moved), normalise(RAW))

    def test_whitespace_is_invisible(self) -> None:
        """Indentation and blank lines are layout, not surface."""
        spaced = RAW.replace("\t", "    ").replace("\n", "\n\n")
        self.assertEqual(normalise(spaced), normalise(RAW))

    def test_type_annotation_comments_are_invisible(self) -> None:
        """The Rust type pgrx notes beside each SQL type is a comment."""
        renamed = RAW.replace("/* & str */", "/* &'static str */")
        self.assertNotEqual(renamed, RAW)
        self.assertEqual(normalise(renamed), normalise(RAW))


class Changed(unittest.TestCase):
    """What MUST diff: the surface itself."""

    def test_added_argument_changes_exactly_that_statement(self) -> None:
        """The planted signature change, and nothing else, differs."""
        before = normalise(RAW).splitlines()
        after = normalise(add_argument(RAW)).splitlines()
        self.assertEqual(len(before), len(after))
        changed = [(b, a) for b, a in zip(before, after, strict=True) if b != a]
        self.assertEqual(len(changed), 1)
        self.assertIn('"edtf_level"( "input" TEXT )', changed[0][0])
        self.assertIn('"edtf_level"( "input" TEXT, "_strict" bool )', changed[0][1])

    def test_added_argument_survives_a_line_shift(self) -> None:
        """A real change is not hidden by the shift that accompanies it."""
        self.assertNotEqual(
            normalise(shift_lines(add_argument(RAW), 1)),
            normalise(RAW),
        )

    def test_return_type_change_diffs(self) -> None:
        """A return type is part of the signature."""
        changed = RAW.replace(") RETURNS INT /*", ") RETURNS bigint /*")
        self.assertNotEqual(changed, RAW)
        self.assertNotEqual(normalise(changed), normalise(RAW))

    def test_removed_function_diffs(self) -> None:
        """A dropped object is a surface change an upgrade script owes."""
        head, *blocks = RAW.split(BLOCK)
        fewer = head + "".join(BLOCK + b for b in blocks if "edtf_max" not in b)
        self.assertNotEqual(normalise(fewer), normalise(RAW))

    def test_volatility_change_diffs(self) -> None:
        """Volatility is declared surface, as an index on it depends on it."""
        changed = RAW.replace("IMMUTABLE STRICT", "STABLE STRICT", 1)
        self.assertNotEqual(normalise(changed), normalise(RAW))


class Main(unittest.TestCase):
    """The guard branches of the entry point the task calls."""

    def test_surface_is_written_to_stdout(self) -> None:
        """The green path: the surface on stdout, nothing on stderr."""
        status, out, err = run_main([write(RAW)])
        self.assertEqual((status, out, err), (0, EDTF_SNAPSHOT, ""))

    def test_comment_only_output_is_red_not_an_empty_match(self) -> None:
        """The header block alone is a broken generation, never a match."""
        header = RAW.split(BLOCK, 2)[1]
        status, out, err = run_main([write(BLOCK + header)])
        self.assertEqual((status, out), (1, ""))
        self.assertIn("normalised to nothing", err)

    def test_empty_file_is_red(self) -> None:
        """An empty generation cannot compare equal to an empty snapshot."""
        status, out, err = run_main([write("")])
        self.assertEqual((status, out), (1, ""))
        self.assertIn("normalised to nothing", err)

    def test_missing_file_is_red(self) -> None:
        """A generation that wrote nothing is named, not skipped."""
        missing = str(Path(tempfile.mkdtemp()) / "absent.sql")
        status, out, err = run_main([missing])
        self.assertEqual((status, out), (1, ""))
        self.assertIn("cannot read the generated schema", err)

    def test_wrong_argument_count_is_red(self) -> None:
        """The task passes exactly one path."""
        for argv in ([], ["a", "b"]):
            with self.subTest(argv=argv):
                status, out, err = run_main(argv)
                self.assertEqual((status, out), (1, ""))
                self.assertIn("usage:", err)


if __name__ == "__main__":
    unittest.main()
